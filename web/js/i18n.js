let current = null;

export function detectLang(langs) {
  const list = Array.isArray(langs) ? langs : [langs];
  return list.some((l) => String(l || "").toLowerCase().startsWith("zh"))
    ? "zh"
    : "en";
}

export function getLang() {
  if (LANGS.includes(current)) return current;
  let saved = null;
  try {
    saved = localStorage.getItem(LS_KEY);
  } catch {
    /* 隐私模式下 localStorage 不可用 */
  }
  current = LANGS.includes(saved) ? saved : detectLang(navigator.languages || [navigator.language || ""]);
  return current;
}

export function setLang(lang) {
  current = LANGS.includes(lang) ? lang : "en";
  try {
    localStorage.setItem(LS_KEY, current);
  } catch {
    /* 忽略写入失败（隐私模式） */
  }
  document.documentElement.lang = current === "zh" ? "zh-CN" : "en";
  document.dispatchEvent(new CustomEvent("mviz:lang", { detail: { lang: current } }));
}

export function t(key, params) {
  const dict = DICT[getLang()] || DICT.en;
  let s = dict[key];
  if (s === undefined) s = DICT.zh[key];
  if (s === undefined) return key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

export function applyStatic(root) {
  const scope = root || document;
  scope.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
  });
  scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.dataset.i18nTitle));
  });
  scope.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  });
}

